def test_strict_reader_cannot_enter_while_a_strict_writer_holds_the_dataset(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    inside = threading.Event()
    release = threading.Event()
    outcome: dict[str, object] = {}

    @pystep(dataset_accesses=[WRITE_SCANS])
    def slow_writer(ms: MeasurementSetV2) -> None:
        inside.set()
        assert release.wait(10)
        set_scans(ms, 3)

    @pystep(dataset_accesses=[DatasetAccess(field="ms", mode="read")])
    def reader(ms: MeasurementSetV2) -> None:
        outcome["reader ran"] = True

    def write() -> None:
        outcome["writer"] = slow_writer(ms=ms, **run_kwargs(tmp_path))

    writer = threading.Thread(target=write)
    writer.start()
    assert inside.wait(10)
    try:
        with pytest.raises(DatasetLifecycleUnavailableError, match="claim refused"):
            reader(ms=ms)
    finally:
        release.set()
        writer.join(10)
    assert "reader ran" not in outcome
    assert outcome["writer"].success
    assert reader(ms=ms).success


SCRIPT = """\
import sys
import numpy as np
import casacore.tables as tables

ms, value = sys.argv[1], int(sys.argv[2])
with tables.table(ms, readonly=False, ack=False) as table:
    table.putcol("SCAN_NUMBER", np.full(table.nrows(), value, dtype=np.int32))
sys.exit(3 if value < 0 else 0)
"""


def test_binary_cab_writer_runs_sandboxed_and_rolls_back_on_nonzero_exit(tmp_path):
    import sys

    from shinobi import Cab
    from shinobi.steps.schema import ParamMeta

    class CabInputs(BaseModel):
        script: Path
        ms: MeasurementSetV2
        value: int

    script = tmp_path / "renumber.py"
    script.write_text(SCRIPT)
    cab = Cab(
        name="renumber_tool",
        command=sys.executable,
        inputs_model=CabInputs,
        outputs_model=Empty,
        field_meta={name: ParamMeta(positional=True) for name in ("script", "ms", "value")},
        dataset_accesses=[WRITE_SCANS],
    )
    ms = make_ms(tmp_path / "obs.ms")

    # A relative MS spelling reaches the tool anchored at the workspace,
    # even though it runs in a private sandbox directory.
    assert cab(script=script, ms=Path("obs.ms"), value=6, sandbox=True, **run_kwargs(tmp_path)).success
    assert scans(ms) == [6] * ROWS

    failed = cab(script=script, ms=Path("obs.ms"), value=-1, sandbox=True, **run_kwargs(tmp_path))
    assert not failed.success and failed.returncode == 3
    # The tool wrote -1 before failing; its exact predecessor is back.
    assert scans(ms) == [6] * ROWS
    last = attempts(tmp_path)[-1]
    assert last.phase is DatasetLifecyclePhase.FAILED
    assert last.leaves[0].mutations[0].outcome is DatasetMutationOutcome.ROLLED_BACK


def test_external_closure_refuses_the_exact_restart_guarantee(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    shared = tmp_path / "shared"
    shared.mkdir()
    (ms / "ANTENNA").rename(shared / "ANTENNA")
    with tables.table(str(ms), readonly=False, ack=False) as table:
        table.putkeyword("ANTENNA", f"Table: {(shared / 'ANTENNA').resolve()}")

    # One directory rename cannot restore a closure spanning two roots, so
    # the guarantee is refused rather than half-kept.
    with pytest.raises(DatasetLifecycleUnavailableError, match="external closure resources"):
        renumber(ms=ms, value=7, **run_kwargs(tmp_path))
    assert scans(ms) == [1] * ROWS


