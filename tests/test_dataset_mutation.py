def test_undeclared_schema_change_is_rolled_back_exactly(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    before = dataset_signature(ms.resolve(), tmp_path)

    @pystep(dataset_accesses=[WRITE_SCANS])
    def sneaky(ms: MeasurementSetV2) -> None:
        set_scans(ms, 99)
        with tables.table(str(ms), readonly=False, ack=False) as table:
            table.addcols(tables.maketabdesc([tables.makearrcoldesc("MODEL_DATA", 0j, ndim=2)]))

    with pytest.raises(DatasetLifecycleViolationError, match="MAIN columns changed without allow_schema_change"):
        sneaky(ms=ms, **run_kwargs(tmp_path))

    assert scans(ms) == [1] * ROWS
    assert dataset_signature(ms.resolve(), tmp_path) == before
    [attempt] = attempts(tmp_path)
    assert attempt.phase is DatasetLifecyclePhase.FAILED
    [leaf] = attempt.leaves
    assert leaf.outcome == "failed"
    assert leaf.mutations[0].outcome is DatasetMutationOutcome.ROLLED_BACK
    assert get_cache_manifest(str(tmp_path / "cache")).entry("sneaky") is None
    chain = get_journal(str(tmp_path / "cache")).get(chain_id(ms.resolve()))
    assert chain.marker is None


def test_declared_column_creation_is_accepted_and_verified(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    access = DatasetAccess(field="ms", mode="write", columns=DatasetColumns(create=("MODEL_DATA",)), allow_schema_change=True)

    @pystep(dataset_accesses=[access])
    def predict(ms: MeasurementSetV2) -> None:
        with tables.table(str(ms), readonly=False, ack=False) as table:
            table.addcols(tables.maketabdesc([tables.makearrcoldesc("MODEL_DATA", 0j, ndim=2)]))

    @pystep(dataset_accesses=[access])
    def forgetful(ms: MeasurementSetV2) -> None:
        pass

    assert predict(ms=ms, **run_kwargs(tmp_path)).success
    with tables.table(str(ms), ack=False) as table:
        assert "MODEL_DATA" in table.colnames()
    other = make_ms(tmp_path / "other.ms")
    with pytest.raises(DatasetLifecycleViolationError, match="declared created column"):
        forgetful(ms=other, **run_kwargs(tmp_path))


def test_row_count_change_requires_permission(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")

    @pystep(dataset_accesses=[DatasetAccess(field="ms", mode="write", columns=DatasetColumns(write=("TIME",)))])
    def append(ms: MeasurementSetV2) -> None:
        with tables.table(str(ms), readonly=False, ack=False) as table:
            table.addrows(2)

    with pytest.raises(DatasetLifecycleViolationError, match="row count changed"):
        append(ms=ms, **run_kwargs(tmp_path))
    with tables.table(str(ms), ack=False) as table:
        assert table.nrows() == ROWS

    @pystep(dataset_accesses=[DatasetAccess(field="ms", mode="write", columns=DatasetColumns(write=("TIME",)), allow_row_count_change=True)])
    def append_allowed(ms: MeasurementSetV2) -> None:
        with tables.table(str(ms), readonly=False, ack=False) as table:
            table.addrows(2)

    assert append_allowed(ms=ms, **run_kwargs(tmp_path)).success
    with tables.table(str(ms), ack=False) as table:
        assert table.nrows() == ROWS + 2


