"""Strict MSv2 mutation lifecycle against real casacore tables.

These tests drive the whole local route -- planning, exclusive claim,
recovery, strict snapshot guard, declared postconditions and the attempt
record -- with tiny tables generated by python-casacore, so the structural
observations and signatures are the real ones rather than stand-ins.
"""

from __future__ import annotations

import os
import threading
from pathlib import Path

import pytest
from pydantic import BaseModel

from shinobi import DatasetAccess, MeasurementSetV2, Recipe, pystep
from shinobi.cache import get_cache_manifest
from shinobi.config import AppConfig
from shinobi.dataset_access import DatasetColumns
from shinobi.dataset_lifecycle import (
    DATASET_MUTATION_CAPABILITY,
    DatasetLifecycleAttempt,
    DatasetLifecyclePhase,
    DatasetLifecycleStore,
    DatasetMutationOutcome,
    dataset_signature,
    mutation_committed,
)
from shinobi.exceptions import DatasetLifecycleUnavailableError, DatasetLifecycleViolationError
from shinobi.snapshots import Chain, HeadStatus, chain_id, faults, get_journal, state_name
from shinobi.steps.dispatch import _dispatch
from shinobi.steps.schema import InputRef

tables = pytest.importorskip("casacore.tables")
np = pytest.importorskip("numpy")  # installed with casacore, not by default
if not hasattr(tables, "default_ms"):  # pragma: no cover - depends on the installed build
    pytest.skip("installed python-casacore has no default_ms fixture builder", allow_module_level=True)

ROWS = 4


class MSInput(BaseModel):
    ms: MeasurementSetV2


class Empty(BaseModel):
    pass


def make_ms(path: Path, *, scan: int = 1) -> Path:
    """A minimal valid MSv2: default subtables, a DATA column and a few rows."""

    ms = tables.default_ms(str(path))
    ms.addcols(tables.maketabdesc([tables.makearrcoldesc("DATA", 0j, ndim=2)]))
    ms.addrows(ROWS)
    ms.putcol("SCAN_NUMBER", np.full(ROWS, scan, dtype=np.int32))
    ms.close()
    return path


def scans(path: Path) -> list[int]:
    with tables.table(str(path), ack=False) as ms:
        return [int(value) for value in ms.getcol("SCAN_NUMBER")]


def set_scans(path: Path, value: int) -> None:
    with tables.table(str(path), readonly=False, ack=False) as ms:
        ms.putcol("SCAN_NUMBER", np.full(ms.nrows(), value, dtype=np.int32))


def attempts(workspace: Path) -> list[DatasetLifecycleAttempt]:
    paths = sorted((workspace / ".shinobi" / "dataset-attempts").glob("*.json"), key=os.path.getmtime)
    return [DatasetLifecycleStore(path).attempt() for path in paths]


def run_kwargs(tmp_path: Path, **extra) -> dict:
    return {"cache": True, "cache_dir": str(tmp_path / "cache"), **extra}


@pytest.fixture(autouse=True)
def _workspace(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    yield
    faults.hooks.clear()


WRITE_SCANS = DatasetAccess(field="ms", mode="write", columns=DatasetColumns(write=("SCAN_NUMBER",)))


@pystep(dataset_accesses=[WRITE_SCANS])
def renumber(ms: MeasurementSetV2, value: int) -> None:
    set_scans(ms, value)


@pystep(dataset_accesses=[WRITE_SCANS])
def increment(ms: MeasurementSetV2, by: int) -> None:
    set_scans(ms, scans(ms)[0] + by)


def chain_recipe(first: int = 10, by: int = 1) -> Recipe:
    recipe = Recipe(name="chain", inputs_model=MSInput, outputs_model=Empty)
    recipe.add_step("renumber", renumber, ms=InputRef(field="ms"), value=first)
    recipe.add_step("increment", increment, ms=InputRef(field="ms"), by=by)
    return recipe


# -- the normal path ---------------------------------------------------------


def test_writer_commits_named_predecessor_and_successor(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    before = dataset_signature(ms.resolve(), tmp_path)

    result = renumber(ms=ms, value=7, **run_kwargs(tmp_path))

    assert result.success
    assert scans(ms) == [7] * ROWS
    [attempt] = attempts(tmp_path)
    assert attempt.schema_version == 2
    assert attempt.capability == DATASET_MUTATION_CAPABILITY
    assert attempt.phase is DatasetLifecyclePhase.COMMITTED
    [leaf] = attempt.leaves
    assert leaf.outcome == "committed"
    assert leaf.cache is not None and leaf.cache.decision == "miss"
    assert any("path string only" in line for line in leaf.cache.dataset_coverage)
    [mutation] = leaf.mutations
    assert mutation.outcome is DatasetMutationOutcome.COMMITTED
    assert mutation.predecessor_state is not None and mutation.predecessor_state.startswith("gen0__")
    assert mutation.predecessor_signature == before
    # A value-only write keeps the structure, and the record says it does
    # not cover values rather than implying the dataset is unchanged.
    assert mutation.successor_signature == before
    assert "not examined" in mutation.signature_coverage
    assert mutation.successor_state == state_name(leaf.cache.cache_key, "ms")
    assert mutation.predecessor_snapshot is not None and mutation.predecessor_snapshot.is_dir()
    assert mutation.successor_snapshot is not None and mutation.successor_snapshot.is_dir()
    assert scans(mutation.predecessor_snapshot) == [1] * ROWS
    assert scans(mutation.successor_snapshot) == [7] * ROWS
    chain = get_journal(str(tmp_path / "cache")).get(chain_id(ms.resolve()))
    assert chain is not None and chain.head == mutation.successor_state and chain.marker is None
    assert chain.generation(chain.head).parent == mutation.predecessor_state
    assert mutation_committed(
        tmp_path / ".shinobi" / "dataset-attempts" / f"{attempt.attempt_id}.json",
        attempt_id=attempt.attempt_id,
        step_path="renumber",
        cache_key=leaf.cache.cache_key,
    )


def test_create_write_read_chain_commits_every_leaf(tmp_path):
    @pystep(dataset_accesses=[DatasetAccess(field="ms", mode="create")])
    def simulate(ms: MeasurementSetV2) -> None:
        make_ms(ms, scan=3)

    seen: list[int] = []

    @pystep(dataset_accesses=[DatasetAccess(field="ms", mode="read")])
    def inspect(ms: MeasurementSetV2) -> None:
        seen.extend(scans(ms))

    recipe = Recipe(name="pipeline", inputs_model=MSInput, outputs_model=Empty)
    recipe.add_step("simulate", simulate, ms=InputRef(field="ms"))
    recipe.add_step("increment", increment, ms=InputRef(field="ms"), by=2)
    recipe.add_step("inspect", inspect, ms=InputRef(field="ms"))

    result = recipe(ms=tmp_path / "new.ms", **run_kwargs(tmp_path))

    assert result.success
    assert seen == [5] * ROWS
    [attempt] = attempts(tmp_path)
    assert attempt.phase is DatasetLifecyclePhase.COMMITTED
    assert attempt.absent_roots == ((tmp_path / "new.ms").resolve(),)
    leaves = {leaf.step_path: leaf for leaf in attempt.leaves}
    assert set(leaves) == {"pipeline.simulate", "pipeline.increment", "pipeline.inspect"}
    assert all(leaf.outcome == "committed" for leaf in leaves.values())
    [created] = leaves["pipeline.simulate"].mutations
    assert created.predecessor_state is None and created.predecessor_signature is None
    assert leaves["pipeline.simulate"].absent_before == ((tmp_path / "new.ms").resolve(),)
    [written] = leaves["pipeline.increment"].mutations
    # The writer consumed exactly the state the creator produced.
    assert written.predecessor_state == created.successor_state
    assert leaves["pipeline.inspect"].mutations == ()


def test_full_rerun_reuses_every_strict_step(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    recipe = chain_recipe()

    assert recipe(ms=ms, **run_kwargs(tmp_path)).success
    assert scans(ms) == [11] * ROWS

    # Were either step to run again, `increment` would move the value on.
    assert recipe(ms=ms, **run_kwargs(tmp_path)).success
    assert scans(ms) == [11] * ROWS
    second = attempts(tmp_path)[-1]
    decisions = {leaf.step_path: leaf.cache.decision for leaf in second.leaves}
    assert decisions == {"chain.renumber": "hit", "chain.increment": "hit"}
    assert all(leaf.outcome == "reused" for leaf in second.leaves)


# -- re-running a mid-chain step --------------------------------------------


def test_changed_mutating_step_restores_its_exact_predecessor(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    assert chain_recipe(first=10, by=1)(ms=ms, **run_kwargs(tmp_path)).success
    assert scans(ms) == [11] * ROWS

    # Only the second step changed. Without restoring its predecessor it
    # would increment the *post-chain* value (11 -> 16); exact recovery makes
    # it increment what `renumber` produced (10 -> 15).
    assert chain_recipe(first=10, by=5)(ms=ms, **run_kwargs(tmp_path)).success
    assert scans(ms) == [15] * ROWS
    last = attempts(tmp_path)[-1]
    decisions = {leaf.step_path: leaf.cache.decision for leaf in last.leaves}
    assert decisions == {"chain.renumber": "hit", "chain.increment": "miss"}
    increment_leaf = next(leaf for leaf in last.leaves if leaf.step_path == "chain.increment")
    renumber_state = state_name(next(leaf for leaf in last.leaves if leaf.step_path == "chain.renumber").cache.cache_key, "ms")
    assert increment_leaf.mutations[0].predecessor_state == renumber_state


def test_same_key_upstream_rerun_rejects_the_stale_downstream_hit(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    assert chain_recipe()(ms=ms, **run_kwargs(tmp_path)).success
    # Forget only the first step's cache entry: it re-runs with the same
    # key, moving the dataset back to its own product. The second step's
    # key and outputs still match, but its work is no longer on disk.
    get_cache_manifest(str(tmp_path / "cache")).remove({"chain.renumber"})

    assert chain_recipe()(ms=ms, **run_kwargs(tmp_path)).success

    assert scans(ms) == [11] * ROWS
    last = attempts(tmp_path)[-1]
    increment_leaf = next(leaf for leaf in last.leaves if leaf.step_path == "chain.increment")
    assert increment_leaf.cache.decision == "rejected-hit"
    assert "does not descend" in increment_leaf.cache.reason
    assert increment_leaf.outcome == "committed"


