def test_failing_writer_leaves_its_exact_predecessor_and_retry_succeeds(tmp_path):
    ms = make_ms(tmp_path / "obs.ms")
    attempts_made = []

    @pystep(dataset_accesses=[WRITE_SCANS])
    def flaky(ms: MeasurementSetV2) -> None:
        set_scans(ms, 42)
        attempts_made.append(1)
        if len(attempts_made) == 1:
            raise RuntimeError("tool crashed after a partial write")

    with pytest.raises(RuntimeError, match="partial write"):
        flaky(ms=ms, **run_kwargs(tmp_path))
    assert scans(ms) == [1] * ROWS
    failed = attempts(tmp_path)[-1]
    assert failed.phase is DatasetLifecyclePhase.FAILED
    assert failed.leaves[0].mutations[0].outcome is DatasetMutationOutcome.ROLLED_BACK

    assert flaky(ms=ms, **run_kwargs(tmp_path)).success
    assert scans(ms) == [42] * ROWS


